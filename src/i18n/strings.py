TABLES = {"zh": ZH, "en": EN}

# 兼容旧名
STRINGS = TABLES


class Translator:
    def __init__(self, lang="zh"):
        self.lang = lang if lang in TABLES else "zh"

    def set_lang(self, lang):
        if lang in TABLES:
            self.lang = lang

    @property
    def table(self):
        return TABLES[self.lang]

    def __call__(self, key, **fmt):
        raw = self.table.get(key)
        if raw is None:
            return "⟦%s⟧" % key
        if fmt:
            try:
                return raw.format(**fmt)
            except (KeyError, IndexError):
                return raw
        return raw

    # 便捷方法
    def tr(self, key, **fmt):
        return self(key, **fmt)


